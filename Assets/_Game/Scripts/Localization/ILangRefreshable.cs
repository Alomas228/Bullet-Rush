/// <summary>
/// UI, который строит текст сам через Lang.Get и поэтому не
/// переводится автоматически: в поле уже лежит «ИГРАТЬ», а не
/// ключ, и LangBinder не может его восстановить.
///
/// Такие компоненты подписываются на Lang.OnLanguageChanged
/// через LangBinder.NotifyRefreshables и пересобирают только текст,
/// не трогая состояние игры и видимость панелей.
/// </summary>
public interface ILangRefreshable
{
    /// <summary>
    /// Перерисовать текст на новом языке. Вызывается в момент
    /// смены языка, когда панель уже открыта и видна игроку.
    /// Реализация не должна менять состояние — только подписи.
    /// </summary>
    void RefreshLang();
}