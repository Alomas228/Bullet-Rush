// Архетип волны задаёт «характер» волны: кто в ней преобладает
// и как сильно она давит. Волны чередуют архетипы по циклу,
// чтобы каждая следующая волна ощущалась иначе.
public enum WaveArchetype
{
    // Сбалансированная смесь всех типов.
    Standard,

    // Массы быстрых бегунов, короткие приёмы и плотные батчи.
    Swarm,

    // Дальние атаки из-за блоков + живучие впереди.
    Siege,

    // Элита выходит вперёд, под прикрытием обычных.
    Hunt
}