using System;

// Модификатор волны — лёгкий акцент поверх архетипа.
// Архетип отвечает на вопрос «какая это волна», модификатор —
// «что в ней не так». Никаких новых врагов, ассетов и систем:
// модификатор только перекачивает веса существующих типов и включает
// уже существующие механики — быстрые рывки, зоны урона, элиту.
[Flags]
public enum WaveModifier
{
    None = 0,

    // Доля быстрых бегунов заметно выше обычной.
    FastAssault = 1 << 0,

    // Больше дальников: стоять и переживать перестаёт работать.
    RangedAssault = 1 << 1,

    // Элита — центральная угроза волны, выходит с задержкой.
    EliteHunt = 1 << 2,

    // Приёмы волны выходят с нескольких направлений по очереди.
    Ambush = 1 << 3,

    // Посреди волны периодически появляются опасные зоны.
    DangerZone = 1 << 4,

    // В конце волны — небольшая пачка сильных врагов.
    LastStand = 1 << 5
}

public static class WaveModifierExtensions
{
    public static bool Has(
        this WaveModifier modifier,
        WaveModifier flag)
    {
        return (modifier & flag) != WaveModifier.None;
    }
}